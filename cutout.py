# -*- coding: utf-8 -*-
"""Вырезание фона и подготовка картинки под стикер Telegram.

Зачем отдельный модуль: генерация отдаёт фотографию с фоном, а стикер без
прозрачности выглядит наклеенным прямоугольником. Плюс правки съезжают по
кадру — модель то приближает лицо, то отдаляет, — и в наборе рядом это видно.
Оба вопроса закрываются одним проходом: маска, обрезка по найденному объекту,
общий квадрат.

Почему ONNX, а не rembg: rembg тянет numba, opencv и scikit-image — под 400 МБ
ради одной маски. onnxruntime у нас уже стоит ради whisperx, numpy и PIL тоже,
поэтому модель гоняем напрямую. Веса (isnet-general-use, ~170 МБ) лежат рядом с
сервисом в ./models и в гит не идут.

Считает на процессоре: маска для одной картинки — доли секунды, а карту в это
время держать незачем.
"""
import hashlib
import io
import os
import threading
from collections import OrderedDict

import numpy as np
from PIL import Image, ImageFilter

# Путь к весам. Файл монтируется с хоста вместе с каталогом сервиса, поэтому
# переживает пересборку образа.
#
# BiRefNet lite, а не isnet, с которого начинали. isnet терял бледную руку на
# бледной стене: маска в этом месте проваливалась, и дыра на тёмной панели
# Telegram читалась как чёрная рука. Лечить это обработкой маски невозможно —
# четыре подхода (сырая альфа, два порога, усиление) дали четыре разных вида
# одного провала. BiRefNet справляется на всех кадрах замера.
#
# Из трёх вариантов BiRefNet взят lite: на наших картинках он неотличим от
# полного, но вдвое быстрее (7.6 с против 12.5) и впятеро меньше (224 МБ против
# 972). Полный и portrait лежат рядом в models/, переключаются этой переменной.
MODEL_PATH = os.getenv("CUTOUT_MODEL", "/root/models/birefnet-lite.onnx")

# Нормализация входа как при обучении BiRefNet — ImageNet.
_MEAN = np.array([0.485, 0.456, 0.406], dtype=np.float32)
_STD = np.array([0.229, 0.224, 0.225], dtype=np.float32)

# Сторона входа сети.
_INPUT = 1024

# Сторона квадрата на выходе. 512 — требование Telegram к стикеру.
CANVAS = int(os.getenv("STICKER_SIZE", "512"))

# Поля вокруг объекта, доля от его большей стороны. Без них голова упирается в
# край и стикер выглядит обрезанным.
MARGIN = 0.06

# Порог маски для поиска границ объекта. Ниже — считаем прозрачным.
_ALPHA_FLOOR = 8

# Потолок коррекции тона, доля. 1.15 = не светлее и не темнее исходника больше
# чем на 15% по каналу. Нужен как предохранитель: если эталон или результат
# посчитались по мусору, коррекция испортит картинку, а ограниченная — лишь
# слегка её подкрасит. Замеренные сдвиги в разы меньше потолка.
TONE_LIMIT = float(os.getenv("STICKER_TONE_LIMIT", "1.15"))

# Порог уверенности маски для СТАТИСТИКИ (не для прозрачности): берём только то,
# в чём сеть уверена, иначе в среднее затечёт фон по полупрозрачному краю.
_TONE_ALPHA = 200

# Меньше этого числа пикселей кожи — считаем, что не нашли, и не корректируем.
_TONE_MIN_PIXELS = 2000

# Эталон тона считается по исходнику, а это ещё один проход маски (6.5 с на
# процессоре). Набор из десяти стикеров приходит десятью НЕЗАВИСИМЫМИ задачами с
# одним и тем же исходником, поэтому эталон кешируется по хешу его байт и
# считается один раз на набор. Четыре записи — это четыре набора подряд, больше
# держать незачем.
_REF_CACHE_MAX = 4
_ref_cache = OrderedDict()
# Свой замок, НЕ _lock: под _lock сидит создание сессии onnxruntime, а
# threading.Lock не рекурсивный — вычисление эталона вызывает _mask и повесило бы
# процесс на себе же.
_ref_lock = threading.Lock()

# Усиление альфы. Сырой выход сети только УМНОЖАЕТСЯ и обрезается единицей:
# уверенная середина объекта становится полностью непрозрачной, а всё
# сомнительное лишь подрастает и никогда не обнуляется.
#
# История двух неудачных попыток, чтобы никто не повторил. Сперва альфа бралась
# сырой — сеть отдаёт середину объекта значением около 230, и человек целиком
# выходил полупрозрачным: на тёмной панели Telegram сквозь него просвечивал фон.
# Потом я поставил ступеньку 0.35-0.65 — стало хуже: всё, в чём сеть не уверена,
# уходило в ноль, и на косплейном фото у человека вырезало руку начисто, а
# чёрная дыра на её месте читалась как «чёрная кожа». Ступенька 0.20-0.50 вела
# себя так же на трёх кадрах из четырёх.
#
# Умножение свободно от этого по устройству: оно монотонно и не может убрать
# то, что сеть хоть как-то нашла. Слабая маска даст полупрозрачную руку —
# некрасиво, но лучше дыры.
_ALPHA_GAIN = 1 / 0.80

# Завал неуверенной части альфы. Применяется ПОСЛЕ усиления и только к ней:
# умножение уже подняло уверенную середину объекта к единице, а единица в любой
# степени единица, поэтому тело этот показатель не трогает вовсе.
#
# Зачем он нужен. Между прядями волос сеть даёт не ноль и не единицу, а 0.2-0.5,
# и пиксель там — чистый фон. Мы оставляли его полупрозрачным, с его же цветом:
# на тёмной панели Telegram светлое небо под альфой 0.3 читается как серое пятно
# между прядями. Это не ореол по контуру волоса, а именно невычищенный фон.
#
# Замер 02.10.2026 на трёх кадрах (волосы по ветру на небе, кудри на светлом
# фоне, бледная блондинка у белой стены). Полупрозрачного фона, пикселей:
# 11297 -> 1576, 4997 -> 529, 807 -> 434. Цена: неуверенный край объекта
# становится прозрачнее, 0.84 -> 0.73 в среднем.
#
# Степень 3 чистит ещё лучше (348 пикселей), но и край съедает заметнее (0.64).
# Двойка — середина, на которой край волос ещё виден, а дымки уже нет.
#
# Главное, чем этот приём отличается от ступенек, на которых я горел дважды
# (см. выше): он монотонный и ничего не обнуляет. Бледная рука на бледной стене
# станет чуть прозрачнее, но не исчезнет — проверено на том самом кадре, оба
# варианта там неотличимы.
_ALPHA_FALLOFF = 2

# --- Экран -------------------------------------------------------------------
#
# Самое точное вырезание получается не из маски, а из цвета: модель правки умеет
# заменить фон сплошной заливкой И ПРОСОВЫВАЕТ ЕЁ МЕЖДУ ПРЯДЯМИ ВОЛОС, куда
# сегментирующая сеть не достаёт никогда. Поэтому промт стикера просит экран, а
# здесь мы его снимаем. Экрана нет (старый бот, txt2img, модель не послушалась)
# — всё идёт по-старому, через маску.
#
# ЦВЕТ ЭКРАНА НЕ ЗАШИТ: он читается с рамки кадра. Так бот волен просить тот
# цвет, которого на человеке нет, и ему не нужно ни о чём договариваться с
# сервисом — сервис смотрит, что приехало.
#
# Зачем понадобилось. Зелёный экран съедал зелёную толстовку, и развести их
# порогом нельзя в принципе: замер 02.10.2026 на нарочно собранном кадре
# (ярко-зелёная толстовка на зелёном экране) дал расстояние по цветности до
# экрана 0.023-0.06 у толстовки — ровно там же, где налёт экрана в волосах
# (0.016-0.14). Любое правило, которое чистит одно, стирает и второе. Остаётся
# не ставить человека и фон в один цвет с самого начала.

# Ключ по ПРЕВЫШЕНИЮ главного канала экрана над большим из двух остальных. Для
# зелёного это привычное g - max(r, b). Кожа, волосы и трава ведут себя
# предсказуемо: у зелёной листвы превышение редко больше 40, у хромакея оно
# за 100.
_TINT_LO = 10.0
_TINT_HI = 60.0

# Второй ключ, по ЦВЕТНОСТИ: насколько цвет пикселя отличается от цвета экрана,
# если забыть про яркость.
#
# Зачем он нужен. Первый ключ считает превышение абсолютной разницей каналов, и
# затенённый экран — тот, что проглядывает между прядями и оттого тёмный, — до
# неё не дотягивает. Цветность же у тени ровно та же, что у освещённого экрана:
# тень делит все три канала поровну.
#
# Замер 02.10.2026 на семи кадрах. Расстояние по цветности до цвета экрана:
# сам фон 0.004-0.005, человек 0.17-0.21, а невычищенные остатки между прядями —
# 0.06-0.14, то есть ровно между. Отсюда и порог.
#
# Шире брать нельзя: на 0.06-0.18 начинает подъедать тёмно-зелёный свитер
# (дыр в объекте 2.9% против 0.2%).
_CHROMA_LO = 0.05
_CHROMA_HI = 0.16

# Экран опознаём по рамке кадра: фон по определению на краях.
#
# Два условия, и оба нужны. ОДНОЦВЕТНОСТЬ — какая доля рамки близка к её же
# медиане. НАСЫЩЕННОСТЬ — насколько цвет рамки далёк от серого; без неё белая
# стена тоже сошла бы за экран, а вырезать по цвету на ней нечего, там работает
# сеть.
#
# Замер 02.10.2026 на 33 кадрах: у кадра с экраном рамка одноцветна на
# 72.7-89.0% при насыщенности 0.168-0.356, у обычной фотографии в комнате —
# 1.7% и 0.048. Пороги стоят в промежутке, далеко от обеих сторон.
_SCREEN_BORDER = 0.5
_SCREEN_SAT = 0.12

# Где сеть уверена, что это человек, цвет с ней не спорит.
#
# Без этой страховки экран — опасная штука: на человеке в зелёной толстовке
# зелёный экран съел 70% объекта, оставив голову и кисти рук. Поэтому решение
# разделено. КТО человек — отвечает сеть, она знает про людей. ГДЕ РОВНО идёт
# край — отвечает цвет, он видит просветы между волосинками. Уверенная часть
# маски остаётся непрозрачной, что бы ни думал про неё цвет: толстовка цела
# (замер 02.10.2026 — от объекта осталось 100%).
_GUARD = 0.90
_GUARD_SOFT = 0.05

# ...но страховка НЕ распространяется на пиксели, которые в точности цвет
# экрана: такой пиксель человеком быть не может, что бы ни думала сеть.
#
# Без этого уточнения страховка защищала ровно то, что мы пришли убрать.
# Сеть уверенно заливает человеком просветы между прядями и дыру между рукой и
# телом — это её известная слабость, с неё всё и началось, — и страховка
# оставляла их непрозрачными. Фон там теперь не комната, а ярко-зелёный, то
# есть получалось ХУЖЕ, чем до экрана. Видено на живом наборе 02.10.2026.
#
# Порог взят с большим запасом в обе стороны (замер 02.10.2026): настоящий фон
# отстоит от своего же медианного цвета на 2-3 единицы, 95% его пикселей — в
# пределах 4. Зелёная толстовка отстоит минимум на 35, зелёный блик на волосах —
# на 36. Между 4 и 35 ставим 16. Этим же допуском меряется одноцветность рамки.
_SCREEN_TOL = 16.0

# Второе условие для страховки: заливка под её защитой должна быть ТОЛСТОЙ.
#
# Одного цвета мало. Между прядями остаётся не чистый экран, а его цвет,
# смешанный с волосами: до порога по цвету он не дотягивает, и страховка его
# берегла. Но одежда — это сплошное пятно в сотни пикселей, а налёт в волосах —
# ниточки. Поэтому маску заливки «открываем»: стираем на k и возвращаем назад.
# Тонкое исчезает насовсем, толстое восстанавливается целиком.
#
# Считаем на четверти разрешения — хватает с избытком и стоит копейки. Пятёрка
# там это двадцать пикселей в полном кадре: всё окрашенное тоньше двадцати
# считаем налётом. Замер 02.10.2026: зелёная толстовка сохраняет 98.8% своих
# пикселей, зелень в волосах теряет 85%.
_THICK = 5
_THICK_SCALE = 4

# Для проверки толщины заливкой считается ЛЮБОЙ подкрашенный пиксель, а не
# только похожий на экран. Со строгим порогом тени на зелёной толстовке в
# «зелёное» не попадали, пятно получалось дырявым, и его рвало на части — видно
# на замере 02.10.2026. Для ниточек в волосах послабление безвредно: вокруг них
# волосы, а они не окрашены ни по какому порогу, так что ниточка остаётся
# ниточкой.
_TINT_ANY = 0.9

# Подавление налёта: главный канал экрана не может быть выше соседних больше
# чем на столько.
_DESPILL = 8.0

# Где давим налёт. Везде, где сеть не уверена, ПЛЮС полоса такой ширины внутрь
# от края: экран подсвечивает волосы и на пару пикселей вглубь, куда маска
# уже уверенно говорит «человек». Внутренность объекта не трогаем вовсе, иначе
# одежда в цвет экрана посереет.
#
# Девятка — это четыре пикселя внутрь, замер 02.10.2026: зелёного внутри объекта
# 250 -> 63 пикселя, при этом зелёная толстовка теряет 0.9 единицы яркости из
# 130.
#
# Шире НЕ ставить, проверено 02.10.2026 на 12 живых кадрах и на нарочно
# собранном злом кадре с ярко-зелёной толстовкой. Полоса 21/33/45 убирает
# остаток в волосах (14916 -> 4466 -> 554 -> 23 пикселя), но тускнеет 37/56/69%
# толстовки, и глазами это уже не «потускнела», а пятнистая болотная каша.
# Выигрыш в волосах при этом едва заметен: прядь остаётся окрашенной, лишь
# темнеет.
_BAND = 9

# Чем резать. "auto" — так работает бот: есть зелёный экран, край ищем по
# цвету, нет — по сетке. "net" — всегда по сетке, цвет про прозрачность не
# спрашиваем вовсе (он там только глушит налёт по кромке).
#
# Режим "net" нужен для сравнения способов на ОДНОМ кадре: замер 02.10.2026
# показал, что birefnet-lite оставляет 0.03% фона на собранных кадрах, но
# собраны они были с идеальным краем волос, и на живых наборах метрика
# бессильна — судить приходится глазами, рядом.
CUT_AUTO = "auto"
CUT_NET = "net"
CUT_MODES = (CUT_AUTO, CUT_NET)

_session = None
_lock = threading.Lock()


def available():
    """Есть ли чем резать. False — стикеры просто не предлагаем."""
    return os.path.exists(MODEL_PATH)


def _get_session():
    """Сессия onnxruntime, одна на процесс.

    Создаётся лениво: модуль импортируется в каждом воркере, а весит модель
    170 МБ, и поднимать её тем, кто стикеров не считает, незачем.
    """
    global _session
    with _lock:
        if _session is None:
            import onnxruntime

            opts = onnxruntime.SessionOptions()
            # Матирование идёт рядом с генерацией на той же машине, и отдавать
            # ему все ядра — значит отнимать их у того, что считает карта.
            opts.intra_op_num_threads = 8
            _session = onnxruntime.InferenceSession(
                MODEL_PATH, opts, providers=["CPUExecutionProvider"])

    return _session


def _mask(image):
    """Маска объекта в размер исходной картинки, uint8 0..255."""
    session = _get_session()
    name = session.get_inputs()[0].name

    small = image.convert("RGB").resize((_INPUT, _INPUT), Image.LANCZOS)
    x = (np.asarray(small, dtype=np.float32) / 255.0 - _MEAN) / _STD
    x = np.transpose(x, (2, 0, 1))[None].astype(np.float32)

    # Сеть отдаёт несколько карт разного масштаба, нужна последняя — самая
    # подробная. И это логиты, поэтому сигмоида.
    out = session.run(None, {name: x})[-1]
    out = out[0][0] if out.ndim == 4 else out[0]
    out = 1.0 / (1.0 + np.exp(-out))

    # Усиление, а не порог. См. _ALPHA_GAIN и _ALPHA_FALLOFF.
    out = np.clip(out * _ALPHA_GAIN, 0.0, 1.0) ** _ALPHA_FALLOFF

    return np.asarray(
        Image.fromarray((out * 255).astype(np.uint8)).resize(image.size,
                                                             Image.LANCZOS))


def _screen_colour(rgb):
    """Цвет экрана или None, если фона одного цвета на кадре нет.

    См. _SCREEN_BORDER и _SCREEN_SAT: читаем рамку, берём её медиану и
    требуем, чтобы рамка была к ней близка и чтобы цвет был насыщенным.
    """
    border = np.concatenate([rgb[0], rgb[-1], rgb[:, 0], rgb[:, -1]])
    med = np.median(border, axis=0)
    flat = np.abs(border - med).max(1) <= _SCREEN_TOL
    if float(flat.mean()) < _SCREEN_BORDER:
        return None

    screen = np.median(border[flat], axis=0)
    chroma = screen / max(float(screen.sum()), 1.0)
    if float(np.abs(chroma - 1.0 / 3.0).max()) < _SCREEN_SAT:
        return None

    return screen


def _screen_axis(screen):
    """Главный канал экрана. По нему считается ключ и по нему же давится налёт."""
    return int(np.argmax(screen))


def _others(rgb, axis):
    """Больший из двух каналов, кроме главного."""
    rest = [i for i in (0, 1, 2) if i != axis]

    return np.maximum(rgb[..., rest[0]], rgb[..., rest[1]])


def _tint_alpha(rgb, axis):
    """Прозрачность по цвету экрана: 0 — чистый экран, 1 — его тут нет."""
    key = rgb[..., axis] - _others(rgb, axis)

    return 1.0 - np.clip((key - _TINT_LO) / (_TINT_HI - _TINT_LO), 0.0, 1.0)


def _chroma_alpha(rgb, screen):
    """Прозрачность по цветности: 0 — цвет экрана любой яркости. См. _CHROMA_LO."""
    if screen is None:
        return np.ones(rgb.shape[:2], dtype=np.float32)

    ref = screen / max(float(screen.sum()), 1.0)
    cur = rgb / np.maximum(rgb.sum(2, keepdims=True), 1.0)
    dist = np.abs(cur - ref).max(2)

    return np.clip((dist - _CHROMA_LO) / (_CHROMA_HI - _CHROMA_LO), 0.0, 1.0)


def _is_screen(rgb, screen):
    """Пиксели, которые в точности цвет экрана. См. _SCREEN_TOL."""
    return np.abs(rgb - screen).max(2) <= _SCREEN_TOL


def _thick_tint(tint):
    """Где заливка — сплошное пятно, а не ниточки. См. _THICK."""
    h, w = tint.shape
    small = Image.fromarray(((tint < _TINT_ANY) * 255).astype(np.uint8)).resize(
        (max(w // _THICK_SCALE, 1), max(h // _THICK_SCALE, 1)), Image.NEAREST)
    small = small.filter(ImageFilter.MinFilter(_THICK))
    small = small.filter(ImageFilter.MaxFilter(_THICK))

    return np.asarray(small.resize((w, h), Image.NEAREST)) > 127


def _despill(rgb, alpha, axis, unsure=None):
    """Картинка без налёта экрана по кромке объекта. См. _BAND."""
    edge = Image.fromarray((alpha * 255).astype(np.uint8))
    band = np.asarray(edge.filter(ImageFilter.MinFilter(_BAND))) < 250
    if unsure is not None:
        band = band | unsure

    out = rgb.copy()
    out[..., axis] = np.where(
        band, np.minimum(rgb[..., axis], _others(rgb, axis) + _DESPILL),
        rgb[..., axis])

    return Image.fromarray(out.astype(np.uint8), "RGB")


def _cut(image, mode=CUT_AUTO):
    """Альфа объекта и картинка без налёта экрана по кромке.

    Возвращает то же, что раньше возвращала одна _mask, если экрана на кадре
    нет или выбран режим CUT_NET. Подробности выбора — в комментариях выше.
    """
    rgb = np.asarray(image, dtype=np.float32)
    screen = _screen_colour(rgb)

    # Прозрачность целиком с сетки. Цвет здесь не решает ничего: если экран
    # всё-таки есть (промт его просил), он только глушит налёт по кромке,
    # иначе на волосах останется кайма и способ будет оболган.
    if mode == CUT_NET or screen is None:
        alpha = _mask(image)
        if screen is None:
            return alpha, image

        return alpha, _despill(rgb, alpha / 255.0, _screen_axis(screen))

    # Два ключа, и прозрачным пиксель считается, если ЛЮБОЙ из них так решил:
    # один ловит яркий экран, другой — его же в тени за прядями.
    axis = _screen_axis(screen)
    key = np.minimum(_tint_alpha(rgb, axis), _chroma_alpha(rgb, screen))

    guard = np.clip((_mask(image) / 255.0 - _GUARD) / _GUARD_SOFT, 0.0, 1.0)
    # Страховка бережёт только то, что и в цвет экрана, и не экран, и сплошное.
    guard = np.where(_is_screen(rgb, screen) | ~_thick_tint(key), 0.0, guard)
    alpha = np.maximum(key, guard)

    return (alpha * 255).astype(np.uint8), _despill(rgb, alpha, axis,
                                                    guard < 1.0)


def _skin(rgb, subject):
    """Пиксели кожи внутри объекта: правило по цветности YCrCb.

    Фон исключается ОБЯЗАТЕЛЬНО, и это не придирка. Бежевая стена проходит по
    цветности как кожа; на замере 01.10.2026 она дала 500 тысяч «пикселей кожи»
    из миллиона и сдвинула среднее так, что я сделал неверный вывод о причине
    сдвига тона. Поэтому маска объекта тут первым условием.
    """
    r, g, b = rgb[..., 0], rgb[..., 1], rgb[..., 2]
    y = 0.299 * r + 0.587 * g + 0.114 * b
    cr = (r - y) * 0.713 + 128
    cb = (b - y) * 0.564 + 128

    return (subject & (cr > 135) & (cr < 180)
            & (cb > 85) & (cb < 135) & (y > 40))


def _skin_mean(rgb, subject):
    """Средний RGB кожи или None, если кожи толком не нашлось."""
    m = _skin(rgb, subject)
    if m.sum() < _TONE_MIN_PIXELS:
        return None

    return rgb[m].mean(axis=0)


def _skin_ref(source_bytes):
    """Эталонный тон кожи по исходной фотографии. None — не вышло.

    Результат кешируется по хешу байт: см. _REF_CACHE_MAX.
    """
    key = hashlib.sha1(source_bytes).hexdigest()
    with _ref_lock:
        if key in _ref_cache:
            _ref_cache.move_to_end(key)
            return _ref_cache[key]

        try:
            src = Image.open(io.BytesIO(source_bytes)).convert("RGB")
            ref = _skin_mean(np.asarray(src, dtype=np.float32),
                             _mask(src) > _TONE_ALPHA)
        except Exception as e:
            print(f"[cutout] эталон тона не посчитался: "
                  f"{type(e).__name__}: {e}", flush=True)
            ref = None

        _ref_cache[key] = ref
        if len(_ref_cache) > _REF_CACHE_MAX:
            _ref_cache.popitem(last=False)

    return ref


def _match_tone(rgba, source_bytes):
    """Вернуть готовый квадрат с тоном кожи как на исходнике.

    Зачем: каждый проход правки отдаёт картинку чуть темнее входа, и сдвиг
    ОБЩИЙ множительный — замерено 01.10.2026 на одном кадре: кожа -2.1%,
    волосы с одеждой -2.0%. Потому и лечится усилением по каналам на весь
    кадр, а не подкраской кожи: подкраска оставила бы шов на границе волос.

    Зачем вообще: сдвиг накапливается (фотография -> дополнить макушку ->
    эмоция) и у разных эмоций разный. На замере из одного фото яркость кожи:
    исходник 170.4, после правки макушки 160.7, стикеры 155.8-165.9. Десять
    стикеров рядом в панели Telegram расходились на 10 единиц из 255 — это и
    видно как «у части сменился тон кожи». Разброс даёт ПРОМТ, не зерно: два
    прогона одной эмоции с разными зёрнами разошлись на 1 единицу, а laugh и
    deadpan — на 10. Фиксировать зерно набора поэтому бессмысленно.

    Считается по ГОТОВОМУ квадрату, а не по кадру до обрезки: в кадре есть
    кожа, которая в стикер не попадает (руки, шея ниже обреза), и усиление по
    ней метит мимо того, что человек увидит. На замере той же четвёрки
    коррекция сводит набор к эталону с точностью 0.3 единицы из 255 (было
    10.1): 159.8-160.1 против эталона 160.6, усиление от 0.967 на laugh до
    1.025 на sad.

    Осторожно при проверке: если пересчитать «кожу» ПОСЛЕ коррекции, правило
    YCrCb выберет уже другой набор пикселей, и разброс покажется 5.7. Это шум
    метрики, а не остаточный сдвиг — мерить надо по тому же набору, по которому
    считалось усиление.
    """
    arr = np.asarray(rgba, dtype=np.float32)
    rgb, alpha = arr[..., :3], arr[..., 3]

    ref = _skin_ref(source_bytes)
    cur = _skin_mean(rgb, alpha > _TONE_ALPHA)
    if ref is None or cur is None:
        return rgba

    gain = np.clip(ref / np.maximum(cur, 1.0), 1 / TONE_LIMIT, TONE_LIMIT)
    out = np.dstack([np.clip(rgb * gain, 0, 255), alpha])
    return Image.fromarray(out.astype(np.uint8), "RGBA")


def _bbox(alpha):
    """Границы непрозрачного. None — маска пустая."""
    ys, xs = np.where(alpha > _ALPHA_FLOOR)
    if not len(xs):
        return None

    return int(xs.min()), int(ys.min()), int(xs.max()) + 1, int(ys.max()) + 1


def to_sticker(png_bytes, source=None, mode=CUT_AUTO):
    """Байты картинки -> байты PNG 512x512 с прозрачным фоном.

    ``source`` — байты исходной фотографии, если картинка получена правкой. По
    ней выравнивается тон кожи, см. _match_tone. Без неё всё работает как
    раньше, только тон не трогается: у txt2img исходника нет.

    ``mode`` — чем искать край, CUT_AUTO или CUT_NET. См. CUT_MODES.

    Возвращает None, если резать нечем или маска пустая: тогда вызывающий
    отдаёт исходную картинку, а не роняет задачу. Стикер — украшение поверх
    генерации, и ронять из-за него уже посчитанное нельзя.
    """
    if not available():
        return None

    try:
        image = Image.open(io.BytesIO(png_bytes)).convert("RGB")
        alpha, image = _cut(image, mode)
        box = _bbox(alpha)
        if box is None:
            return None

        rgba = image.convert("RGBA")
        rgba.putalpha(Image.fromarray(alpha))

        # Квадрат вокруг объекта: берём большую сторону, добавляем поля и
        # центрируем. Именно это выравнивает кадр между стикерами набора —
        # что бы модель ни сделала с масштабом лица, на выходе объект занимает
        # одну и ту же долю квадрата.
        x0, y0, x1, y1 = box
        side = max(x1 - x0, y1 - y0)
        side = int(side * (1 + 2 * MARGIN))
        cx, cy = (x0 + x1) // 2, (y0 + y1) // 2
        crop = (cx - side // 2, cy - side // 2, cx + side // 2, cy + side // 2)

        # Вылезающий за края квадрат дорисовываем прозрачным, а не двигаем
        # внутрь: сдвиг сбил бы центровку, ради которой всё и затевалось.
        square = Image.new("RGBA", (side, side), (0, 0, 0, 0))
        square.paste(rgba.crop(crop), (0, 0))

        square = square.resize((CANVAS, CANVAS), Image.LANCZOS)

        # Тон выравниваем последним шагом, по тем же пикселям, что человек и
        # увидит. См. _match_tone.
        if source is not None:
            square = _match_tone(square, source)

        out = io.BytesIO()
        square.save(out, "PNG", optimize=True)
        return out.getvalue()
    except Exception as e:
        print(f"[cutout] не вырезал фон: {type(e).__name__}: {e}", flush=True)
        return None
